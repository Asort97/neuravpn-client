"""Portable structural checks; Xcode compilation remains the authoritative gate."""
from pathlib import Path
import plistlib
import re

IOS = Path(__file__).resolve().parents[1]
source = (IOS / "Runner.xcodeproj/project.pbxproj").read_text(encoding="utf-8")
tokens = re.findall(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|[^\s{}()=;,]+|[{}()=;,]',
                    source, flags=re.S)
tokens = [t for t in tokens if not t.startswith(("//", "/*"))]
position = 0


def take(expected=None):
    global position
    token = tokens[position]
    position += 1
    if expected is not None:
        assert token == expected, (position, expected, token)
    return token


def value():
    token = take()
    if token == "{":
        result = {}
        while tokens[position] != "}":
            key = take().strip('"')
            assert key not in result, f"Duplicate key {key}"
            take("=")
            result[key] = value()
            take(";")
        take("}")
        return result
    if token == "(":
        result = []
        while tokens[position] != ")":
            result.append(value())
            if tokens[position] != ")":
                take(",")
        take(")")
        return result
    assert token not in "}=;,)", (position, token)
    return token.strip('"')


project = value()
assert position == len(tokens)
objects = project["objects"]
references = {t for t in tokens if re.fullmatch(r"[A-F0-9]{24}", t)}
assert not references - objects.keys(), f"Unresolved object IDs: {references - objects.keys()}"
root = objects[project["rootObject"]]
targets = {objects[key]["name"]: objects[key] for key in root["targets"]}
runner, tunnel = targets["Runner"], targets["PacketTunnel"]
assert tunnel["productType"] == "com.apple.product-type.app-extension"
assert any(objects[d]["target"] in root["targets"] and
           objects[objects[d]["target"]]["name"] == "PacketTunnel"
           for d in runner["dependencies"])
embed = [objects[b] for b in runner["buildPhases"]
         if objects[b].get("name") == "Embed App Extensions"]
assert len(embed) == 1 and embed[0]["dstSubfolderSpec"] == "13"
assert any(objects[f]["fileRef"] == tunnel["productReference"] for f in embed[0]["files"])

for target in (runner, tunnel):
    configurations = objects[target["buildConfigurationList"]]["buildConfigurations"]
    assert {objects[c]["name"] for c in configurations} == {"Debug", "Release", "Profile"}

project_configs = objects[root["buildConfigurationList"]]["buildConfigurations"]
assert all(float(objects[c]["buildSettings"]["IPHONEOS_DEPLOYMENT_TARGET"]) >= 15
           for c in project_configs)


def visit_group(key, parent):
    obj = objects[key]
    kind = obj["isa"]
    path = parent / obj.get("path", "")
    if kind in ("PBXGroup", "PBXVariantGroup"):
        for child in obj["children"]:
            visit_group(child, path)
    elif kind == "PBXFileReference" and obj.get("sourceTree") != "BUILT_PRODUCTS_DIR":
        # Generated by Flutter or the SHA-verified native dependency step.
        if path.name in ("GeneratedPluginRegistrant.m", "GeneratedPluginRegistrant.h", "Generated.xcconfig"):
            return
        if path.suffix == ".xcframework":
            return
        assert path.exists(), f"Missing referenced file: {path}"


visit_group(root["mainGroup"], IOS)
for relative in ("Runner/Info.plist", "PacketTunnel/Info.plist", "Flutter/AppFrameworkInfo.plist",
                 "Runner/Runner.entitlements", "PacketTunnel/PacketTunnel.entitlements"):
    with (IOS / relative).open("rb") as file:
        content = plistlib.load(file)
    if relative.endswith("entitlements"):
        assert content["com.apple.security.application-groups"] == ["group.com.neuravpn.app"]
        assert content["com.apple.developer.networking.networkextension"] == ["packet-tunnel-provider"]

print(f"Validated {len(objects)} Xcode objects: all IDs resolve, sources exist, extension is embedded,")
print("Runner depends on PacketTunnel, three configurations are present, plists/entitlements parse.")
